const LangContext = React.createContext({ lang: 'en', t: (k) => k, setLang: () => {} });

function LangProvider({ children }){
  const [lang, setLang] = React.useState(() => {
    try { return localStorage.getItem('nhj-lang') || 'en'; } catch (e) { return 'en'; }
  });
  React.useEffect(() => {
    try { localStorage.setItem('nhj-lang', lang); } catch (e) {}
    document.documentElement.lang = lang;
    document.documentElement.dir  = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.classList.toggle('rtl', lang === 'ar');
  }, [lang]);

  const t = React.useCallback((k, vars = {}) => {
    let s = (STRINGS[lang] && STRINGS[lang][k]) || STRINGS.en[k] || k;
    if (vars) Object.keys(vars).forEach(v => { s = s.split('{'+v+'}').join(vars[v]); });
    return s;
  }, [lang]);

  return <LangContext.Provider value={{ lang, t, setLang }}>{children}</LangContext.Provider>;
}

function useLang(){ return React.useContext(LangContext); }

export { LangProvider, useLang, STRINGS };
